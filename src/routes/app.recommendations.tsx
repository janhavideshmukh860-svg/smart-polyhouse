import { createFileRoute } from "@tanstack/react-router";
import { DEMO_MODE, DEMO_BADGE, demoRecommendations } from "@/lib/demo-data";
import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { Lightbulb } from "lucide-react";
import { PageHeader } from "@/components/AppShell";
import { EmptyState, ErrorState, LoadingState } from "@/components/states";
import { KeyValue, LayerLabel, Pill, SectionCard, urgencyTone, statusTone } from "@/components/data-bits";
import { Button } from "@/components/ui/button";
import { api } from "@/lib/api";
import { fmt, fmtTime } from "@/lib/features";
import { usePolyhouse } from "@/lib/polyhouse";

export const Route = createFileRoute("/app/recommendations")({
  head: () => ({
    meta: [
      { title: "Recommendations — Smart Polyhouse" },
      {
        name: "description",
        content: "Every irrigation and plant-health recommendation generated by the backend.",
      },
      { property: "og:title", content: "Recommendations — Smart Polyhouse" },
      {
        property: "og:description",
        content: "Every irrigation and plant-health recommendation generated by the backend.",
      },
    ],
  }),
  component: RecommendationsPage,
});

const DOMAINS = ["all", "irrigation", "disease"] as const;

function RecommendationsPage() {
  const { activeId, active } = usePolyhouse();
  const [domain, setDomain] = useState<(typeof DOMAINS)[number]>("all");

  const { data, isLoading, error, refetch } = useQuery({
    queryKey: ["recommendations", activeId, domain],
    queryFn: DEMO_MODE ? () => Promise.resolve(demoRecommendations) : () => api.listRecommendations(activeId ?? undefined, 50, domain === "all" ? undefined : domain),
    enabled: DEMO_MODE || !!activeId,
  });

  return (
    <div className="mx-auto max-w-6xl space-y-6">
      <PageHeader
        title="Recommendations"
        description={`Persisted backend recommendations${active ? ` for ${active.name}` : ""}.`}
      />

      {DEMO_MODE ? <Pill tone="warning" className="text-[10px]">{DEMO_BADGE}</Pill> : null}

      <div className="flex flex-wrap items-center gap-2">
        <LayerLabel layer="recommendation" />
        {DOMAINS.map((d) => (
          <Button
            key={d}
            size="sm"
            variant={domain === d ? "default" : "outline"}
            onClick={() => setDomain(d)}
          >
            {d}
          </Button>
        ))}
      </div>

      {!activeId ? (
        <EmptyState
          title="No polyhouse selected"
          description="Recommendations are scoped to a polyhouse."
        />
      ) : isLoading ? (
        <LoadingState label="Loading recommendations…" />
      ) : error ? (
        <ErrorState error={error} onRetry={() => void refetch()} />
      ) : (data?.recommendations.length ?? 0) === 0 ? (
        <EmptyState
          icon={<Lightbulb className="h-5 w-5" />}
          title="No recommendations yet"
          description="Recommendations appear here after the backend generates them from real decisions."
        />
      ) : (
        <div className="space-y-4">
          {data!.recommendations.map((r) => (
            <SectionCard
              key={r.id}
              title={r.recommendation_text}
              description={r.reason}
              action={
                <div className="flex flex-wrap gap-2">
                  <Pill tone={urgencyTone(r.urgency)}>{r.urgency}</Pill>
                  <Pill tone={statusTone(r.status)}>{r.status}</Pill>
                </div>
              }
            >
              <div className="grid gap-x-8 sm:grid-cols-2">
                <KeyValue label="Domain" value={r.domain} />
                <KeyValue label="Created" value={fmtTime(r.created_at)} />
                <KeyValue
                  label="Model confidence"
                  value={
                    r.model_confidence === null
                      ? "Not reported"
                      : fmt(r.model_confidence * 100, 1, " %")
                  }
                />
              </div>
              {r.risk_factors && r.risk_factors.length > 0 ? (
                <div className="mt-3 flex flex-wrap gap-2">
                  {r.risk_factors.map((f) => (
                    <Pill key={f} tone="warning">
                      {f}
                    </Pill>
                  ))}
                </div>
              ) : null}
            </SectionCard>
          ))}
        </div>
      )}
    </div>
  );
}
